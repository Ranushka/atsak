#!/usr/bin/env node
// Scans packages/ui/src/{atoms,molecules,organisms} and packages/finance-ui/src for
// component files, pulls an optional __DOC ... DOC__ (or __DOC_BLOCK ... DOC__ for a
// full-width demo) comment out of each one, and regenerates the components gallery
// page from them. A component with no __DOC block falls back to a bare `<Name />`.
//
// Run with: pnpm --filter playground run docs:gen
// (also runs automatically before `dev` and `build`, see package.json)
//
// To add a component to the gallery: just add a __DOC block to its source file and
// regenerate — no manual gallery editing needed.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../..");
const outPath = path.join(__dirname, "../src/pages/ComponentsPage.tsx");

const CATEGORIES = [
  { title: "Atoms", icon: "Palette", pkg: "QDS", dir: path.join(repoRoot, "packages/ui/src/atoms") },
  { title: "Molecules", icon: null, pkg: "QDS", dir: path.join(repoRoot, "packages/ui/src/molecules") },
  { title: "Organisms", icon: "Boxes", pkg: "QDS", dir: path.join(repoRoot, "packages/ui/src/organisms") },
  { title: "Finance UI", icon: null, pkg: "Finance", dir: path.join(repoRoot, "packages/finance-ui/src") },
];

// Captures: [1] = "_BLOCK" or undefined (align hint), [2] = doc content.
const DOC_RE = /__DOC(_BLOCK)?\b([\s\S]*?)DOC__/;

function scanCategory({ pkg, dir }) {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".tsx"))
    .sort((a, b) => a.localeCompare(b));

  return files.map((file) => {
    const moduleName = file.replace(/\.tsx$/, "");
    const content = readFileSync(path.join(dir, file), "utf8");
    const match = content.match(DOC_RE);
    const align = match && match[1] ? "block" : "row";
    const demo = match ? match[2].trim() : `<${pkg}.${moduleName} />`;
    return { moduleName, demo, align };
  });
}

function renderSection({ moduleName, demo, align }) {
  return [`          <Section title="${moduleName}" align="${align}">`, demo, `          </Section>`].join("\n");
}

function renderCategory({ title, icon }, components) {
  const heading = icon
    ? `        <h1 className="mb-3 flex items-center gap-2 text-base font-semibold">\n          <Icons.${icon} className="size-4" /> ${title}\n        </h1>`
    : `        <h1 className="mb-3 text-base font-semibold">${title}</h1>`;

  return [
    "      <div>",
    heading,
    '        <div className="flex flex-col gap-6">',
    components.map(renderSection).join("\n"),
    "        </div>",
    "      </div>",
  ].join("\n");
}

const categoryBlocks = CATEGORIES.map((cat) => renderCategory(cat, scanCategory(cat)));
const totalCount = CATEGORIES.reduce((sum, cat) => sum + scanCategory(cat).length, 0);

const file = `// AUTO-GENERATED by apps/playground/scripts/generate-components-page.mjs — do not
// hand-edit this file. Add or change a component's demo by editing the __DOC ... DOC__
// (or __DOC_BLOCK ... DOC__ for a full-width demo) comment in its source file, then run:
//   pnpm --filter playground run docs:gen
import * as React from "react";
import * as QDS from "@qashio/ui";
import * as Finance from "@qashio/finance-ui";
import * as Icons from "lucide-react";

function Section({
  title,
  children,
  align = "row",
}: {
  title: string;
  children: React.ReactNode;
  align?: "row" | "block";
}) {
  return (
    <section className="flex flex-col gap-3">
      <h2 className="text-sm font-semibold uppercase tracking-wide text-muted-foreground">{title}</h2>
      <div
        className={
          align === "row"
            ? "flex flex-wrap items-center gap-4 rounded-lg border border-border bg-surface p-4"
            : "overflow-hidden rounded-lg border border-border bg-surface"
        }
      >
        {children}
      </div>
    </section>
  );
}

export function ComponentsPage() {
  return (
    <div className="flex flex-col gap-8">
      <QDS.PageHeader
        icon={<Icons.LayoutGrid className="size-5" />}
        title="Components"
        description="Every component and variant, grouped by atomic level."
      />

${categoryBlocks.join("\n\n")}

      <div>
        <h1 className="mb-3 text-base font-semibold">Templates</h1>
        <Section title="AdminLayout">
          <p className="text-sm text-muted-foreground">
            [rail][sidebar][topbar + scrollable main], full viewport height — this whole app shell
            (the rail, sidebar, and topbar around this page) <em>is</em> an <code>AdminLayout</code>, so it's
            demonstrated by every page rather than nested here.
          </p>
        </Section>
      </div>
    </div>
  );
}
`;

writeFileSync(outPath, file, "utf8");
console.log(`Generated ${path.relative(repoRoot, outPath)} from ${totalCount} components.`);
